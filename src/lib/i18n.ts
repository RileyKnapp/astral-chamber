for (const language of SUPPORTED_LANGUAGES) {
  Object.assign(
    TRANSLATIONS[language.code],
    APP_ROUTE_TRANSLATIONS.en,
    APP_ROUTE_TRANSLATIONS[language.code],
  );
}

const SUPPORTED_LANGUAGE_CODES = new Set<string>(
  SUPPORTED_LANGUAGES.map((language) => language.code),
);

export function isSupportedLanguage(value: string): value is AppLanguage {
  return SUPPORTED_LANGUAGE_CODES.has(value);
}

export function resolveLanguage(
  setting: LanguageSetting,
  preferredLanguages: readonly string[],
): AppLanguage {
  if (setting !== LANGUAGE_AUTO) return setting;

  for (const preferred of preferredLanguages) {
    const normalized = preferred.toLowerCase();
    if (normalized.startsWith("zh")) return "zh-Hans";
    const base = normalized.split("-")[0];
    const match = SUPPORTED_LANGUAGES.find((language) => language.code.toLowerCase() === base);
    if (match) return match.code;
  }

  return "en";
}

export function getDeviceLanguages(): string[] {
  if (typeof navigator === "undefined") return ["en"];
  return navigator.languages?.length
    ? Array.from(navigator.languages)
    : [navigator.language || "en"];
}

export function translate(language: AppLanguage, key: string): string {
  return TRANSLATIONS[language]?.[key] ?? ENGLISH_TRANSLATIONS[key] ?? key;
}
